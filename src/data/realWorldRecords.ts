/**
 * All real-world records combined (Curated + Official Track Records).
 */
export const ALL_REAL_WORLD_BENCHMARKS: RealWorldRecord[] = [
  ...REAL_WORLD_RECORDS,
  ...HISTORICAL_TRACK_RECORDS,
];

/**
 * Filter real-world records by source type ("all", "curated", or "track_record").
 */
export function getRealWorldRecords(
  source: "all" | RealWorldRecordSource = "all",
): RealWorldRecord[] {
  if (source === "curated") return REAL_WORLD_RECORDS;
  if (source === "track_record") return HISTORICAL_TRACK_RECORDS;
  return ALL_REAL_WORLD_BENCHMARKS;
}

/**
 * Categorize a race trip distance into sprint, mile, route, or staying.
 */
export function getTripCategory(distanceMeters: number): TripCategory {
  if (distanceMeters < 1400) return "sprint";
  if (distanceMeters < 1800) return "mile";
  if (distanceMeters < 2400) return "route";
  return "staying";
}
