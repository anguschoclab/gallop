/**
 * strategyJournal.ts - Player race-plan journal: plans, outcomes and reflections.
 * Outcomes are derived from the horse's raceHistory, never stored twice.
 */
import type { HorseRaceHistoryEntry } from "@/domains/horse/simulation/types";
import { generateUUID } from "@/shared/uuid/uuid";

export const STRATEGY_JOURNAL_MAX = 500;

export interface StrategyJournalEntry {
  id: string;
  createdDay: number;
  horseId: string;
  horseName: string;
  raceId?: string;
  raceName?: string;
  raceDay?: number;
  ridingStyle?: string;
  earlyPosition?: string;
  moveTiming?: string;
  aggressiveness?: number;
  confidence?: number;
  plan: string;
  reflection?: string;
  /** True when the entry was created automatically on race entry. */
  autoGenerated?: boolean;
  /** Filled in automatically once the race is run. */
  result?: {
    position: number;
    fieldSize?: number;
    prizeMoney: number;
    beyer?: number;
    /** Stable cash balance right after the result landed. */
    cashAfter: number;
    filledDay: number;
  };
}

/** Minimal race shape needed to read the plan a horse actually ran with. */
export interface JournalRaceLike {
  entries: Array<{
    horseId: string;
    jockeyInstructions?: {
      ridingStyle: string;
      earlyPosition: string;
      moveTiming: string;
      aggressiveness: number;
    };
  }>;
}

/**
 * Record actual results for any journal plans whose race has now been run.
 * @param list - Journal entries to fill outcomes for
 * @param horses - Horses keyed by id, used to look up race results
 * @param cash - Current player cash balance
 * @param day - Current game day
 * @param races - Optional races, used to copy the jockey plan onto auto-tracked entries
 */
export function fillJournalOutcomes(
  list: StrategyJournalEntry[] | undefined,
  horses: Record<string, { raceHistory?: HorseRaceHistoryEntry[] } | undefined>,
  cash: number,
  day: number,
  races?: Record<string, JournalRaceLike | undefined>,
): StrategyJournalEntry[] | undefined {
  if (!list?.length) return list;
  let changed = false;
  const next = list.map((e) => {
    if (e.result || !e.raceId) return e;
    const run = horses[e.horseId]?.raceHistory?.find((h) => h.raceId === e.raceId);
    if (!run) return e;
    changed = true;
    // Auto-tracked entries carry no plan of their own: record the jockey plan
    // the horse actually ran with, so Plan Effectiveness ranks the real plan.
    const ran = e.ridingStyle
      ? undefined
      : races?.[e.raceId]?.entries.find((x) => x.horseId === e.horseId)?.jockeyInstructions;
    return {
      ...e,
      ...(ran && {
        ridingStyle: ran.ridingStyle,
        earlyPosition: ran.earlyPosition,
        moveTiming: ran.moveTiming,
        aggressiveness: ran.aggressiveness,
      }),
      result: {
        position: run.position,
        fieldSize: run.fieldSize,
        prizeMoney: run.purseEarned ?? 0,
        beyer: run.beyer,
        cashAfter: Math.round(cash),
        filledDay: day,
      },
    };
  });
  return changed ? next : list;
}

export type NewJournalEntry = Omit<StrategyJournalEntry, "id">;

export function addJournalEntry(
  list: StrategyJournalEntry[] | undefined,
  entry: NewJournalEntry,
): StrategyJournalEntry[] {
  // A manual plan logged for an auto-tracked race upgrades the placeholder
  // instead of duplicating it.
  if (entry.raceId) {
    const idx = (list ?? []).findIndex(
      (e) => e.autoGenerated && e.raceId === entry.raceId && e.horseId === entry.horseId,
    );
    if (idx >= 0) {
      return (list ?? []).map((e, i) =>
        i === idx ? { ...e, ...entry, id: e.id, autoGenerated: false } : e,
      );
    }
  }
  const id = `sj-${entry.createdDay}-${entry.horseId}-${(list?.length ?? 0) + 1}-${generateUUID()}`;
  const next = [{ ...entry, id }, ...(list ?? [])];
  if (next.length <= STRATEGY_JOURNAL_MAX) return next;
  // Evict oldest auto-generated entries first so manual plans survive entry spam.
  const overflow = next.length - STRATEGY_JOURNAL_MAX;
  const autos = next.filter((e) => e.autoGenerated);
  const evict = new Set(autos.slice(-overflow).map((e) => e.id));
  return next.filter((e) => !evict.has(e.id)).slice(0, STRATEGY_JOURNAL_MAX);
}

/**
 * True when a journal entry already links this horse to this race.
 * @param list
 * @param raceId
 * @param horseId
 */
export function hasJournalEntryForRace(
  list: StrategyJournalEntry[] | undefined,
  raceId: string,
  horseId: string,
): boolean {
  return (list ?? []).some((e) => e.raceId === raceId && e.horseId === horseId);
}

export interface AutoJournalParams {
  horseId: string;
  horseName: string;
  raceId: string;
  raceName: string;
  raceDay: number;
  createdDay: number;
}

/**
 * Record a lightweight journal entry when a player horse is entered into a
 * race (manual or auto-entry). `fillJournalOutcomes` fills the result once
 * the race resolves. Returns the list unchanged when an entry for the same
 * race + horse already exists.
 * @param list - Current journal entries (may be undefined)
 * @param params - Race entry context
 */
export function autoCreateJournalEntry(
  list: StrategyJournalEntry[] | undefined,
  params: AutoJournalParams,
): StrategyJournalEntry[] {
  if (hasJournalEntryForRace(list, params.raceId, params.horseId)) return list ?? [];
  return addJournalEntry(list, {
    createdDay: params.createdDay,
    horseId: params.horseId,
    horseName: params.horseName,
    raceId: params.raceId,
    raceName: params.raceName,
    raceDay: params.raceDay,
    plan: `Auto-entry: entered in ${params.raceName}.`,
    autoGenerated: true,
  });
}

export function updateJournalEntry(
  list: StrategyJournalEntry[] | undefined,
  id: string,
  patch: Partial<StrategyJournalEntry>,
): StrategyJournalEntry[] {
  return (list ?? []).map((e) => (e.id === id ? { ...e, ...patch, id } : e));
}

export function removeJournalEntry(list: StrategyJournalEntry[] | undefined, id: string) {
  return (list ?? []).filter((e) => e.id !== id);
}

export type JournalOutcome =
  | { status: "pending" }
  | { status: "no-race" }
  | { status: "missing" }
  | { status: "run"; position: number; fieldSize?: number; earned: number; beyer?: number };

export function journalOutcome(
  entry: StrategyJournalEntry,
  history: HorseRaceHistoryEntry[] | undefined,
  currentDay: number,
): JournalOutcome {
  if (!entry.raceId) return { status: "no-race" };
  if (entry.result)
    return {
      status: "run",
      position: entry.result.position,
      fieldSize: entry.result.fieldSize,
      earned: entry.result.prizeMoney,
      beyer: entry.result.beyer,
    };
  const run = history?.find((h) => h.raceId === entry.raceId);
  if (run)
    return {
      status: "run",
      position: run.position,
      fieldSize: run.fieldSize,
      earned: run.purseEarned ?? 0,
      beyer: run.beyer,
    };
  if (entry.raceDay !== undefined && entry.raceDay >= currentDay) return { status: "pending" };
  return { status: "missing" };
}

export type PlanDimension =
  "ridingStyle" | "earlyPosition" | "moveTiming" | "aggression" | "source";

export interface PlanEffectivenessRow {
  key: string;
  runs: number;
  wins: number;
  places: number;
  winRate: number;
  placeRate: number;
  avgFinish: number;
  prizeMoney: number;
  /** 0-100, shrunk toward the journal average for small samples. */
  score: number;
}

function dimensionKey(e: StrategyJournalEntry, dim: PlanDimension): string {
  switch (dim) {
    case "ridingStyle":
      return e.ridingStyle ?? "Custom plan";
    case "earlyPosition":
      return e.earlyPosition ?? "Custom plan";
    case "moveTiming":
      return e.moveTiming ?? "Custom plan";
    case "aggression":
      if (e.aggressiveness === undefined) return "Custom plan";
      return e.aggressiveness < 40
        ? "Patient (0-39)"
        : e.aggressiveness < 70
          ? "Balanced (40-69)"
          : "Aggressive (70-100)";
    case "source":
      return e.ridingStyle ? "Race Advisor plan" : "Custom plan";
  }
}

const PRIOR_RUNS = 3;

/**
 * The plan-effectiveness score for a set of completed runs: 60% win rate,
 * 30% place rate, 10% finish quality. Shared by the journal dimension table
 * and the daily plan view.
 * @param winRate
 * @param placeRate
 * @param finishQuality
 */
export function rawScore(winRate: number, placeRate: number, finishQuality: number) {
  return 100 * (0.6 * winRate + 0.3 * placeRate + 0.1 * finishQuality);
}

/**
 * How often each plan type wins, from journal entries that have a recorded result.
 * @param list - Journal entries with recorded outcomes
 * @param dim - Plan dimension to group by
 */
export function planEffectiveness(
  list: StrategyJournalEntry[] | undefined,
  dim: PlanDimension,
): PlanEffectivenessRow[] {
  const runs = (list ?? []).filter((e) => e.result);
  if (runs.length === 0) return [];
  const quality = (e: StrategyJournalEntry) => {
    const f = e.result!.fieldSize ?? 0;
    return f > 1 ? 1 - (e.result!.position - 1) / (f - 1) : e.result!.position === 1 ? 1 : 0;
  };
  const overall = rawScore(
    runs.filter((e) => e.result!.position === 1).length / runs.length,
    runs.filter((e) => e.result!.position <= 3).length / runs.length,
    runs.reduce((s, e) => s + quality(e), 0) / runs.length,
  );
  const groups = new Map<string, StrategyJournalEntry[]>();
  for (const e of runs) {
    const k = dimensionKey(e, dim);
    groups.set(k, [...(groups.get(k) ?? []), e]);
  }
  return [...groups.entries()]
    .map(([key, es]) => {
      const n = es.length;
      const wins = es.filter((e) => e.result!.position === 1).length;
      const places = es.filter((e) => e.result!.position <= 3).length;
      const raw = rawScore(wins / n, places / n, es.reduce((s, e) => s + quality(e), 0) / n);
      return {
        key,
        runs: n,
        wins,
        places,
        winRate: wins / n,
        placeRate: places / n,
        avgFinish: es.reduce((s, e) => s + e.result!.position, 0) / n,
        prizeMoney: es.reduce((s, e) => s + e.result!.prizeMoney, 0),
        score: Math.round((raw * n + overall * PRIOR_RUNS) / (n + PRIOR_RUNS)),
      };
    })
    .sort((a, b) => b.score - a.score || b.runs - a.runs);
}
