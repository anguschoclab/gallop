import { describe, it, expect } from "vitest";
import {
  addJournalEntry,
  autoCreateJournalEntry,
  fillJournalOutcomes,
  hasJournalEntryForRace,
  STRATEGY_JOURNAL_MAX,
  type StrategyJournalEntry,
} from "@/domains/tactics/simulation/strategyJournal";

const params = {
  horseId: "h1",
  horseName: "Ace",
  raceId: "r1",
  raceName: "Derby Trial",
  raceDay: 20,
  createdDay: 15,
};

const entry = (overrides: Partial<StrategyJournalEntry> = {}): StrategyJournalEntry => ({
  id: "sj-1",
  createdDay: 10,
  horseId: "h1",
  horseName: "Ace",
  plan: "Hand-made plan",
  ...overrides,
});

describe("hasJournalEntryForRace", () => {
  it("returns true when an entry links the same raceId + horseId", () => {
    const list = [entry({ raceId: "r1" }), entry({ id: "sj-2", raceId: "r2" })];
    expect(hasJournalEntryForRace(list, "r1", "h1")).toBe(true);
  });

  it("returns false for a different horse in the same race", () => {
    const list = [entry({ raceId: "r1" })];
    expect(hasJournalEntryForRace(list, "r1", "other")).toBe(false);
  });

  it("returns false on an empty or missing list", () => {
    expect(hasJournalEntryForRace(undefined, "r1", "h1")).toBe(false);
    expect(hasJournalEntryForRace([], "r1", "h1")).toBe(false);
  });
});

describe("autoCreateJournalEntry", () => {
  it("creates a marked auto entry with race linkage", () => {
    const [e] = autoCreateJournalEntry(undefined, params);
    expect(e.horseId).toBe("h1");
    expect(e.horseName).toBe("Ace");
    expect(e.raceId).toBe("r1");
    expect(e.raceName).toBe("Derby Trial");
    expect(e.raceDay).toBe(20);
    expect(e.createdDay).toBe(15);
    expect(e.autoGenerated).toBe(true);
    expect(e.id).toContain("sj-");
    expect(e.result).toBeUndefined();
  });

  it("skips creation when an entry for the same raceId + horseId exists", () => {
    const existing = entry({ raceId: "r1" });
    const next = autoCreateJournalEntry([existing], params);
    expect(next).toHaveLength(1);
    expect(next[0].id).toBe("sj-1");
  });

  it("evicts auto-generated entries before hand-made ones at the cap", () => {
    const autos = Array.from({ length: STRATEGY_JOURNAL_MAX }, (_, i) =>
      entry({ id: `auto-${i}`, raceId: `ra-${i}`, autoGenerated: true }),
    );
    const manual = { createdDay: 99, horseId: "h9", horseName: "Star", plan: "Careful ride" };
    const next = addJournalEntry(autos, manual);
    expect(next).toHaveLength(STRATEGY_JOURNAL_MAX);
    expect(next[0].plan).toBe("Careful ride");
    // The new manual entry plus older manual entries are kept; autos evicted first.
    expect(next.filter((e) => e.autoGenerated)).toHaveLength(STRATEGY_JOURNAL_MAX - 1);
  });
});

describe("fillJournalOutcomes", () => {
  const horses = {
    h1: {
      raceHistory: [
        {
          raceId: "r1",
          raceName: "Derby Trial",
          position: 2,
          day: 20,
          purseEarned: 5_000,
          fieldSize: 10,
          beyer: 88,
        },
      ],
    },
  };

  it("fills the result for an auto-generated entry once the race ran", () => {
    const journal = autoCreateJournalEntry(undefined, params);
    const filled = fillJournalOutcomes(journal, horses, 123_000, 21)!;
    expect(filled[0].result).toMatchObject({
      position: 2,
      fieldSize: 10,
      prizeMoney: 5_000,
      beyer: 88,
      cashAfter: 123_000,
      filledDay: 21,
    });
  });

  it("records the jockey plan the horse ran with on an auto-tracked entry", () => {
    const journal = autoCreateJournalEntry(undefined, params);
    const races = {
      [params.raceId]: {
        entries: [
          {
            horseId: params.horseId,
            jockeyInstructions: {
              ridingStyle: "closer",
              earlyPosition: "drop_back",
              moveTiming: "late",
              aggressiveness: 75,
            },
          },
        ],
      },
    };
    const filled = fillJournalOutcomes(journal, horses, 123_000, 21, races)!;
    expect(filled[0].ridingStyle).toBe("closer");
    expect(filled[0].moveTiming).toBe("late");
    expect(filled[0].aggressiveness).toBe(75);
  });

  it("leaves entries without a recorded run unchanged", () => {
    const journal = autoCreateJournalEntry(undefined, params);
    const filled = fillJournalOutcomes(journal, { h1: { raceHistory: [] } }, 0, 21);
    expect(filled).toBe(journal);
  });

  it("does not overwrite an existing result", () => {
    const journal = [
      entry({
        raceId: "r1",
        result: { position: 1, prizeMoney: 9_000, cashAfter: 1, filledDay: 19 },
      }),
    ];
    const filled = fillJournalOutcomes(journal, horses, 123_000, 21)!;
    expect(filled[0].result!.position).toBe(1);
  });
});
